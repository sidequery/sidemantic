//! Local metadata for the bundled DAX function-name catalog.
//!
//! Signatures are transcribed from the Microsoft Learn DAX reference at the
//! pinned `MicrosoftDocs/query-docs` revision recorded below. `None` means the
//! official reference did not establish that field; it never means unlimited
//! unless the field's documentation says so.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResultKind {
    Scalar,
    Table,
    Special,
    Unknown,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ArgumentCategory {
    Scalar,
    Table,
    ColumnOrTable,
    Column,
    Measure,
    Filter,
    OrderBy,
    PartitionBy,
    MatchBy,
    TypeName,
    Enum,
    Unknown,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RepeatPattern {
    pub start: u8,
    pub width: u8,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FunctionSignature {
    pub name: &'static str,
    pub min_args: Option<u8>,
    pub max_args: Option<u8>,
    pub repeat: Option<RepeatPattern>,
    pub result: ResultKind,
    /// Categories follow documented positional arguments. For variadic
    /// signatures, the repeating suffix is described by `repeat`.
    pub arguments: &'static [ArgumentCategory],
    /// Positions that may be represented by an omitted argument when a later
    /// positional argument is supplied. Empty does not imply omission is invalid;
    /// it means Microsoft Learn did not document a positional hole.
    pub omittable_positions: &'static [u8],
    pub source: Option<&'static str>,
}

